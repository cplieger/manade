package egress

import (
	"net/netip"
	"slices"
	"testing"
)

func TestParseResolvConf(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		name, file string
		want       []netip.Addr
		unknown    bool
	}{
		{
			name: "docker 24 on a user-defined network",
			file: "nameserver 127.0.0.11\noptions ndots:0\n",
			// Docker 24 writes no ExtServers comment, so where its resolver
			// forwards cannot be read.
			unknown: true,
		},
		{
			name: "a newer docker on a user-defined network",
			file: "nameserver 127.0.0.11\noptions ndots:0\n\n# Based on host file: '/etc/resolv.conf' (internal resolver)\n" +
				"# ExtServers: [host(10.0.0.53) host(10.0.0.54)]\n# Overrides: []\n# Option ndots from: internal\n",
			want: []netip.Addr{addr("10.0.0.53"), addr("10.0.0.54")},
		},
		{
			name: "docker's default bridge",
			file: "# Generated by NetworkManager\nsearch lan\nnameserver 10.0.0.53\nnameserver\t10.0.0.54\r\n",
			want: []netip.Addr{addr("10.0.0.53"), addr("10.0.0.54")},
		},
		{
			name: "an override and a loopback upstream",
			file: "nameserver 127.0.0.11\n# ExtServers: [8.8.8.8 host(127.0.0.53)]\n",
			want: []netip.Addr{addr("8.8.8.8"), addr("127.0.0.53")},
		},
		{
			name: "named first, each once",
			file: "nameserver fd00::53\nnameserver 10.0.0.53\nnameserver 10.0.0.53\n# ExtServers: [host(10.0.0.53) 1.1.1.1]\n",
			want: []netip.Addr{addr("fd00::53"), addr("10.0.0.53"), addr("1.1.1.1")},
		},
		{
			name: "lines the C library skips",
			file: "#nameserver 10.0.0.1\n; nameserver 10.0.0.2\nnameserver\nnameserver resolver.lan\nnameservers 10.0.0.3\n nameserver 10.0.0.4 \n",
			want: []netip.Addr{addr("10.0.0.4")},
		},
		{
			name: "a zone left out",
			file: "nameserver fe80::1%eth0\n# ExtServers: [host(fe80::1%2)]\n",
			want: []netip.Addr{addr("fe80::1")},
		},
		{
			name: "mapped IPv4 read as IPv4",
			file: "nameserver ::ffff:10.0.0.53\nnameserver ::ffff:127.0.0.11\n# ExtServers: [host(::ffff:10.0.0.54)]\n",
			want: []netip.Addr{addr("10.0.0.53"), addr("10.0.0.54")},
		},
		{name: "empty", unknown: true},
		{name: "an empty ExtServers comment", file: "nameserver 127.0.0.11\n# ExtServers: []\n", unknown: true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got := ParseResolvConf([]byte(tc.file))
			if !slices.Equal(got.Addrs, tc.want) {
				t.Errorf("Addrs = %v, want %v", got.Addrs, tc.want)
			}
			if got.Unknown != tc.unknown {
				t.Errorf("Unknown = %v, want %v", got.Unknown, tc.unknown)
			}
		})
	}
}
